// scripts/build-hook.mjs: bundle src/entry.ts into hooks/reflect-hook.mjs.
//
// A plugin install is a git clone: no `npm install`, no dist/. So the hook ships
// as committed ES modules with the Anthropic SDK inside them, and the npm bin
// points at the same entry file. The SDK sits in a chunk under hooks/lib/ that
// only the judge and the reflection import, so the hooks that run on every tool
// call do not parse it. The licences of everything bundled are written to
// hooks/THIRD_PARTY_LICENSES.txt.
//
//   node scripts/build-hook.mjs           write hooks/reflect-hook.mjs, hooks/lib/, the licences
//   node scripts/build-hook.mjs --check   exit 1 if any of them is stale (CI)

import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const HOOKS = join(root, "hooks");
const LIB = join(HOOKS, "lib");
const NOTICES = join(HOOKS, "THIRD_PARTY_LICENSES.txt");
const check = process.argv.includes("--check");

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const result = await build({
  absWorkingDir: root,
  entryPoints: { "reflect-hook": "src/entry.ts" },
  outdir: HOOKS,
  entryNames: "[name]",
  chunkNames: "lib/[name]-[hash]",
  outExtension: { ".js": ".mjs" },
  splitting: true,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  write: false,
  metafile: true,
  legalComments: "none",
  charset: "utf8",
  banner: {
    js: [
      "#!/usr/bin/env node",
      `// ${pkg.name} ${pkg.version}. Generated by scripts/build-hook.mjs from src/; do not edit.`,
      "// Third-party code bundled here is listed with its licence in hooks/THIRD_PARTY_LICENSES.txt.",
      // Some bundled CommonJS reaches for require(); give it one.
      'import { createRequire as __reflectCreateRequire } from "node:module";',
      "const require = __reflectCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "warning",
});

const outputs = result.outputFiles.map((f) => [f.path, f.text]);

// ─── licences of the bundled packages ───────────────────────────────────

const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const parts = input.split(/[\\/]/);
  const i = parts.lastIndexOf("node_modules");
  if (i < 0) continue;
  const name = parts[i + 1]?.startsWith("@") ? `${parts[i + 1]}/${parts[i + 2]}` : parts[i + 1];
  const dir = join(root, ...parts.slice(0, i + 1), ...name.split("/"));
  if (!packages.has(name)) packages.set(name, dir);
}

function licenceText(dir) {
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n));
  return f ? readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim() : null;
}

const blocks = [...packages.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, dir]) => {
    const p = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const text = licenceText(dir) ?? `(no licence file in the package; package.json says ${p.license})`;
    const notice = existsSync(join(dir, "NOTICE")) ? "\n\nNOTICE\n\n" + readFileSync(join(dir, "NOTICE"), "utf8").trim() : "";
    return `${name}@${p.version} (${p.license})\n${"-".repeat(60)}\n${text}${notice}`;
  });

const notices =
  "hooks/reflect-hook.mjs and hooks/lib/ bundle the following packages. reflect itself is MIT (see LICENSE).\n\n" +
  blocks.join("\n\n\n") +
  "\n";

// ─── write or compare ───────────────────────────────────────────────────

const targets = [...outputs, [NOTICES, notices]];
const rel = (f) => relative(root, f).split(sep).join("/");
const existingChunks = existsSync(LIB) ? readdirSync(LIB).map((n) => join(LIB, n)) : [];
const leftovers = existingChunks.filter((f) => !outputs.some(([p]) => p === f));

if (check) {
  const stale = targets.filter(([f, want]) => !existsSync(f) || readFileSync(f, "utf8").replace(/\r\n/g, "\n") !== want);
  for (const [f] of stale) console.error(`stale: ${rel(f)} (run npm run build)`);
  for (const f of leftovers) console.error(`left over: ${rel(f)} (run npm run build)`);
  process.exit(stale.length || leftovers.length ? 1 : 0);
}

mkdirSync(LIB, { recursive: true });
for (const f of leftovers) rmSync(f);
for (const [f, text] of targets) writeFileSync(f, text);
for (const [f, text] of outputs) console.log(`${rel(f).padEnd(36)} ${(Buffer.byteLength(text) / 1024).toFixed(0).padStart(5)} KB`);
console.log(`${packages.size} bundled packages: ${[...packages.keys()].join(", ")}`);
